import { fromWei, toWei } from '@/utils/wei';

// Every expected value is what web3 4.16 returned for toWei(value, 'ether')
// and fromWei(wei, 'ether'), which these replace.
describe('wei', () => {
  it.each<[number | string, bigint]>([
    [0, 0n],
    [1, 1_000_000_000_000_000_000n],
    [12, 12_000_000_000_000_000_000n],
    [1.5, 1_500_000_000_000_000_000n],
    [0.1, 100_000_000_000_000_000n],
    [0.30000000000000004, 300_000_000_000_000_040n],
    [0.6153846153846154, 615_384_615_384_615_400n],
    [1 / 3, 333_333_333_333_333_300n],
    [123456.789, 123_456_789_000_000_000_000_000n],
    [2 ** 53, 9_007_199_254_740_992_000_000_000_000_000_000n],
    [-1.5, -1_500_000_000_000_000_000n],
    // JavaScript prints these with an exponent.
    [1.2e-7, 120_000_000_000n],
    [1e-7, 100_000_000_000n],
    [3.5e-12, 3_500_000n],
    [5e-19, 0n],
    [1e21, 10n ** 39n],
    // Past the 18th decimal: dropped, not rounded.
    [0.000012345678901234567, 12_345_678_901_234n],
    ['0.1234567890123456789', 123_456_789_012_345_678n],
    ['1.9999999999999999999', 1_999_999_999_999_999_999n],
    ['1.5', 1_500_000_000_000_000_000n],
    [(1.05 / 1.3).toString(), 807_692_307_692_307_700n],
  ])('toWei(%p) is %p', (amount, wei) => {
    expect(toWei(amount)).toBe(wei);
  });

  it.each<[bigint, number]>([
    [0n, 0],
    [1n, 1e-18],
    [1_000_000_000_000_000_000n, 1],
    [1_500_000_000_000_000_000n, 1.5],
    [123_456_789_012_345_678_901n, 123.456789012345678901],
  ])('fromWei(%p) is %p', (wei, amount) => {
    expect(fromWei(wei)).toBe(amount);
  });

  it('rejects what is not a number', () => {
    expect(() => toWei('DIMO')).toThrow();
  });
});
