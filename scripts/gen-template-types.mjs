#!/usr/bin/env node
// The template contract is definitions-worker/schema/template.schema.json,
// served at <definitionsWorkerUrl>/schema/. Console generates from it rather
// than hand-writing a third copy (the worker's TS and dd-api's Go are the
// other two).
//
// The generator reads a VENDORED copy of the schema, not the network. Two
// reasons. A generator whose input can change underneath it produces output
// nobody can reproduce -- the same command on the same commit gives different
// answers depending on what is deployed that minute. And drift is only
// reviewable if it appears in a diff: `--from` rewrites the vendored schema
// alongside the types, so a contract change shows up as both files moving
// together in the same commit.
//
//   npm run gen:template-types                 regenerate types from the vendored schema
//   npm run gen:template-types -- --from <url|path>   pull a new contract, then regenerate
//   npm run check:template-types               fail if the committed types are stale
import { compile } from 'json-schema-to-typescript';
import { writeFile, readFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const SCHEMA = new URL('../src/types/generated/template.schema.json', import.meta.url);
const OUT = new URL('../src/types/generated/template.ts', import.meta.url);

const BANNER = `/* eslint-disable */
// GENERATED by scripts/gen-template-types.mjs from
// src/types/generated/template.schema.json, vendored from
// definitions-worker/schema/template.schema.json. Do not edit.
`;

async function load(source) {
  if (source === undefined) return JSON.parse(await readFile(SCHEMA, 'utf8'));
  if (source.startsWith('http')) {
    const resp = await fetch(source);
    if (!resp.ok) throw new Error(`${source} returned ${resp.status}`);
    return resp.json();
  }
  return JSON.parse(await readFile(source, 'utf8'));
}

// Exported so the drift guard runs the real generator rather than a
// reimplementation of it -- a guard that regenerates differently from the
// generator tests nothing.
export async function generate(source) {
  const schema = await load(source);
  const body = await compile(schema, 'Template', {
    bannerComment: '',
    additionalProperties: false,
    // Mirrors definitions-worker/scripts/gen-types.mjs: minItems on trims
    // otherwise generates [Trim, ...Trim[]], which no .map() result can be
    // assigned back to.
    ignoreMinAndMaxItems: true,
    style: { singleQuote: true, semi: true, printWidth: 90 },
  });
  return { schema, types: BANNER + body };
}

const fromFlag = process.argv.indexOf('--from');
const source = fromFlag !== -1 ? process.argv[fromFlag + 1] : undefined;
const check = process.argv.includes('--check');

if (check && source !== undefined) {
  console.error(
    '--check verifies the committed output against the vendored schema; it does not take --from',
  );
  process.exit(2);
}

const { schema, types } = await generate(source);

if (check) {
  const committed = await readFile(OUT, 'utf8').catch(() => null);
  if (committed === types) {
    console.log('src/types/generated/template.ts is up to date with the vendored schema');
    process.exit(0);
  }
  console.error(
    committed === null
      ? 'src/types/generated/template.ts is missing.'
      : 'src/types/generated/template.ts is stale: the vendored schema no longer produces it.',
  );
  console.error('Run `npm run gen:template-types` and commit the result.');
  process.exit(1);
}

await mkdir(new URL('../src/types/generated/', import.meta.url), { recursive: true });
// The schema is rewritten only when one was fetched: a plain regeneration must
// not touch the contract it read.
if (source !== undefined) {
  await writeFile(SCHEMA, `${JSON.stringify(schema, null, 2)}\n`);
  console.log(`vendored ${fileURLToPath(SCHEMA)} from ${source}`);
}
await writeFile(OUT, types);
console.log(`wrote ${fileURLToPath(OUT)}`);
